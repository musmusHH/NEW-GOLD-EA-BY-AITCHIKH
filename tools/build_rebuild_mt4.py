"""Combine the existing MT4 HUD with the user's Fractals entry / dual management EA.
The original MT4/MT5 files are never overwritten. Run with --check to verify output.
"""
from pathlib import Path
import re
import sys
ROOT=Path(__file__).resolve().parents[1]


def replace_function(source,name,replacement=''):
    match=re.search(r'^(?:void|bool|int|double|string)\s+'+name+r'\([^\n]*\)\s*\{',source,re.M)
    if not match: raise ValueError(name)
    i=match.end();depth=1
    while depth:
        depth+=(source[i]=='{')-(source[i]=='}');i+=1
    return source[:match.start()]+replacement+source[i:]


def render():
    source=(ROOT/'gold_x9_FIXED.mq4').read_text()
    inputs=(ROOT/'rebuild/RebuildInputs.mqh').read_text()
    engine=(ROOT/'rebuild/RebuildEngine.mqh').read_text()
    start=source.index('//--- INPUT PARAMETERS ---')
    end=source.index('//--- Chart Style & CARBON GRID HUD ---',start)
    source=source[:start]+'//--- INPUT PARAMETERS ---\n'+inputs+'\n'+source[end:]
    start=source.index('//--- Drawdown Guard ---')
    end=source.index('//--- GLOBAL VARIABLES ---',start)
    source=source[:start]+source[end:]
    unused=['activateStrategyContext','findSwingPoints','runStrategyTick','placeEntry',
            'calculateStrategyLots','NormalizeLots','SendPendingOrder','expireStalePendingOrders']
    for name in unused:
        source=replace_function(source,name)
        source=re.sub(r'^(?:void|bool|double|int)\s+'+name+r'\([^\n]*\);\n','',source,flags=re.M)
    source=replace_function(source,'OnInit','int OnInit()\n  {\n   return RebuildInit();\n  }')
    source=replace_function(source,'OnTick','void OnTick()\n  {\n   RebuildTick();\n  }')
    source=replace_function(source,'OnTimer','void OnTimer()\n  {\n   // Display only: no order submission or management here.\n   UpdateStatus();PanelDraw(false);\n  }')
    source=source.replace('void OnDeinit(const int reason)\n  {','void OnDeinit(const int reason)\n  {\n   if(ShowStatusComment) Comment("");')
    # Both management options honor the user's existing BE/trailing switches.
    source=source.replace('if(favorablePct >= beTrigger)','if(UseBreakEven && favorablePct >= beTrigger)')
    source=source.replace('if(favorablePct >= trTrigger && favorablePct <= maxTrailPct)',
                          'if(UseTrailingStop && favorablePct >= trTrigger && favorablePct <= maxTrailPct)')
    # Percentage management keeps exact legacy actions, with broker-step/ticket safeguards.
    source=source.replace('OrderClose(selTicket, OrderLots(), exitPrice, 30, clrRed)',
                          'OrderClose(selTicket, OrderLots(), exitPrice, SlippagePoints, clrRed)')
    source=source.replace('OrderClose(selTicket, halfLot, exitPrice, 30, clrGold)',
                          'OrderClose(selTicket, halfLot, exitPrice, SlippagePoints, clrGold)')
    source=source.replace('MathFloor(openLots / 2.0 / lotStep) * lotStep, 2)',
                          'MathFloor(openLots / 2.0 / lotStep) * lotStep, RebuildLotDigits(lotStep))')
    source=source.replace('      FixStops(asPendingType, exitPrice, newSL, newTP);', '''      FixStops(asPendingType, exitPrice, newSL, newTP);
      newSL=RebuildPrice(newSL,!isBuy);newTP=RebuildPrice(newTP,isBuy);
      // Never loosen an existing stop after broker-distance/tick adjustments.
      if(curSL>0 && ((isBuy && newSL<curSL) || (!isBuy && newSL>curSL)))newSL=curSL;''')
    source=source.replace('IntegerToString(pendingBuy+pendingSell),UiAmber());',
                          'IntegerToString(pendingBuy+pendingSell)+"/"+IntegerToString(MaxPendingOrders),UiAmber());')
    source=source.replace('filterMatchMode = MATCH_MAGIC_OR_COMMENT','filterMatchMode = MATCH_MAGIC_ONLY')
    source=source.replace('#property version     "6.750"','#property version     "1.110"')
    source=source.replace('#property description "gold X9 Full Focus design 4 + four themes + broker-data chart"',
                          '#property description "Independent MT4 Fractals rebuild + Raised Solid HUD + single/multi Fractals + POINTS/PERCENT management; demo test first."')
    source='''// Independent MT4 reconstruction; NOT the original video's source code.
// User-supplied Fractals/pending strategy with single/multiple Fractal levels and selectable points/percentage management.
// Raised Solid HUD and percentage manager reused from the repository's MT4 v6.750.
// Generated by tools/build_rebuild_mt4.py. See REBUILD_RAISED.md.
'''+source[source.index('#property copyright'):]
    return source+'\n//=== Independent rebuild engine ===\n'+engine


if __name__=='__main__':
    output=ROOT/'gold_x9_Rebuild_Raised.mq4';text=render()
    if '--check' in sys.argv:
        if not output.exists() or output.read_text()!=text:raise SystemExit('Run python tools/build_rebuild_mt4.py')
        print('Rebuild Raised generated source is current')
    else:
        output.write_bytes(text.replace('\n','\r\n').encode());print(output)
